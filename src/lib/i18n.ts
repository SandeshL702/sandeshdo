export type MsgKey = keyof typeof en;

const TABLES: Record<Locale, Record<string, string | string[]>> = {
  en: en as unknown as Record<string, string | string[]>,
  hi: hi as unknown as Record<string, string | string[]>,
};

export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const table = TABLES[locale] ?? TABLES.en;
  const raw = table[key];
  const fallback = TABLES.en[key];
  let s = typeof raw === "string" ? raw : typeof fallback === "string" ? fallback : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function tList(locale: Locale, key: string): string[] {
  const table = TABLES[locale] ?? TABLES.en;
  const raw = table[key];
  if (Array.isArray(raw)) return raw;
  const fb = TABLES.en[key];
  return Array.isArray(fb) ? fb : [];
}

export function useT() {
  const locale = useApp((s) => s.settings.locale ?? "en");
  const translate = useCallback((key: string, vars?: Record<string, string | number>) => t(locale, key, vars), [locale]);
  return { locale, t: translate };
}
